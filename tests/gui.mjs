/** Real browser + real core/log adapter; only the model response is a local fixture. */
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
const server = spawn(process.env.KAIPI_TEST_PYTHON || 'python3', ['scripts/preview.py','--seed','--port','0'], {stdio:['ignore','pipe','inherit']});
let browser;
try {
  const url = await new Promise((resolve,reject) => {
    server.stdout.on('data', chunk => { const match = String(chunk).match(/http:\/\/127\.0\.0\.1:\d+/); if (match) resolve(match[0]); });
    server.on('exit', code => reject(new Error('Preview exited: ' + code)));
  });
  browser = await chromium.launch({executablePath:process.env.CHROMIUM_BIN || undefined, headless:true, args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  const errors=[]; page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.waitForSelector('.turn');
  await page.waitForFunction(()=>document.getElementById('connection').hidden);
  assert.equal(await page.locator('.turn').count(),3);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
  await page.click('#tree-toggle');
  await page.waitForFunction(()=>document.querySelectorAll('.tree-node').length===6);
  await page.locator('.tree-node').filter({hasText:'N3'}).click();
  await page.click('[data-node-action="go"]');
  await page.waitForFunction(()=>document.getElementById('cursor-chip').textContent.includes('N3'));
  assert.equal(await page.locator('.turn').count(),3);
  assert.ok((await page.locator('.turn').last().innerText()).includes('卡片'));
  await page.click('#tree-toggle');
  await page.locator('.tree-node').filter({hasText:'N5'}).click();
  await page.click('[data-node-action="go"]');
  await page.waitForFunction(()=>document.getElementById('cursor-chip').textContent.includes('N5'));
  await page.click('#tree-toggle');
  await page.locator('.tree-node').filter({hasText:'N3'}).click();
  await page.click('[data-node-action="graft"]');
  await page.waitForSelector('#graft-form');
  await page.check('input[value="leaf"]');
  await page.click('#graft-form button[type=submit]');
  await page.waitForFunction(()=>document.querySelectorAll('.graft-chip').length===1);
  await page.click('#tree-close');
  await page.click('[data-unstage]');
  await page.waitForFunction(()=>document.querySelectorAll('.graft-chip').length===0);
  await page.click('#tree-toggle');
  await page.locator('.tree-node').filter({hasText:'N3'}).click();
  await page.click('[data-node-action="archive"]');
  await page.click('#confirm');
  await page.waitForFunction(()=>document.querySelectorAll('.tree-node').length===4);
  await page.check('#show-archived');
  await page.waitForFunction(()=>document.querySelectorAll('.tree-node').length===6);
  await page.locator('.tree-node').filter({hasText:'N3'}).click();
  await page.click('[data-node-action="restore"]');
  await page.waitForFunction(()=>!document.querySelector('.tree-node.selected').classList.contains('archived'));
  await page.click('[data-node-action="pin"]');
  await page.click('#confirm');
  await page.waitForFunction(()=>document.querySelector('.tree-node.current .node-pin')?.textContent.includes('主干'));
  await page.click('#tree-close');
  await page.click('#sidebar-toggle');
  await page.click('#new-chat');
  await page.waitForFunction(()=>!document.getElementById('welcome').hidden);
  const draftSession = await page.locator('.session-item.active').getAttribute('data-session');
  await page.fill('#draft','保留一段未发送的想法');
  await page.click('#sidebar-toggle');
  await page.locator('.session-item').filter({hasText:'让一个想法'}).click();
  await page.waitForFunction(()=>document.getElementById('draft').value==='');
  await page.click('#sidebar-toggle');
  await page.locator(`[data-session="${draftSession}"]`).click();
  await page.waitForFunction(()=>document.getElementById('draft').value==='保留一段未发送的想法');
  await page.click('#send');
  await page.waitForSelector('#live-turn');
  await page.waitForFunction(()=>document.getElementById('send').getAttribute('aria-label')==='停止生成');
  await page.click('#send');
  await page.waitForFunction(()=>document.getElementById('send').getAttribute('aria-label')==='发送消息');
  await page.fill('#draft','继续这个想法');
  await page.click('#send');
  await page.waitForFunction(()=>document.querySelectorAll('.turn:not(#live-turn)').length>=1);
  await page.waitForFunction(()=>!document.getElementById('live-turn'));
  assert.ok((await page.locator('#messages').innerText()).includes('从当前思路继续'));
  await page.fill('#draft','xss-probe');
  await page.click('#send');
  await page.waitForFunction(()=>!document.getElementById('live-turn') && document.querySelectorAll('.turn:not(#live-turn)').length>=2);
  assert.equal(await page.locator('.markdown img,.markdown button,.markdown [data-branch],.markdown a[href^="javascript:"]').count(),0);
  assert.equal(await page.evaluate(()=>window.__injected),undefined);
  await page.click('#model-picker');
  await page.waitForSelector('.model-option');
  await page.click('#manage-models');
  await page.waitForSelector('#provider-form');
  assert.equal(await page.inputValue('#provider-key'),'');
  await page.click('#dialog-close');
  await page.click('#sidebar-toggle');
  await page.click('#appearance-button');
  await page.click('[data-mode="dark"]');
  await page.click('[data-color="indigo"]');
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark' && document.documentElement.dataset.color==='indigo');
  await page.click('#dialog-close');
  await page.reload();
  await page.waitForFunction(()=>document.getElementById('connection').hidden);
  assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),'dark');
  assert.equal(await page.evaluate(()=>document.documentElement.dataset.color),'indigo');
  await page.click('#sidebar-toggle');
  await page.click('#appearance-button');
  await page.click('[data-color="clay"]');
  await page.click('[data-mode="system"]');
  await page.emulateMedia({colorScheme:'light'});
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
  await page.emulateMedia({colorScheme:'dark'});
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark');
  await page.click('#dialog-close');
  await page.click('#sidebar-close');
  // A narrow viewport and a raised keyboard must keep the composer accessible.
  await page.setViewportSize({width:320,height:520});
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
  const composer=await page.locator('#composer').boundingBox();
  assert.ok(composer.y>=0 && composer.y+composer.height<=520);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.evaluate(()=>getComputedStyle(document.querySelector('.send')).transitionDuration),'0s');
  assert.deepEqual(errors,[]);
  console.log('PASS: mobile conversation, branching, graft, archive/restore, pin, drafts, stop/retry, settings, narrow keyboard viewport, reduced motion.');
} finally { await browser?.close(); server.kill('SIGTERM'); }
