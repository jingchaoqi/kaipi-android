/** Real GUI, bridge, core and logs. Only provider responses are deterministic fixtures. */
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';

const server=spawn(process.env.KAIPI_TEST_PYTHON||'python3',['scripts/preview.py','--retry-fixture','--port','0'],{stdio:['ignore','pipe','inherit']});
let browser;
try {
  const url=await new Promise((resolve,reject)=>{server.stdout.on('data',chunk=>{const m=String(chunk).match(/http:\/\/127\.0\.0\.1:\d+/);if(m)resolve(m[0]);});server.on('exit',reject);});
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_BIN||undefined,headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const errors=[], retries=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(request.method()==='POST'&&request.url().endsWith('/rpc')){const body=request.postDataJSON();if(body.op==='retry')retries.push(body);}});
  const settled=()=>page.waitForFunction(()=>!document.getElementById('live-turn')&&document.getElementById('send').getAttribute('aria-label')==='发送消息');
  await page.goto(url);await page.waitForFunction(()=>document.getElementById('connection').hidden);
  assert.equal(await page.locator('[data-retry-turn]').count(),0);
  await page.setInputFiles('#file-input',{name:'original.txt',mimeType:'text/plain',buffer:Buffer.from('FROZEN_BROWSER_ATTACHMENT')});
  await page.waitForSelector('.attachment-chip');
  const question='retry-once 请阅读原始附件 [file1]';
  await page.fill('#draft',question);await page.click('#send');
  await page.waitForSelector('.retry-panel');await settled();
  const failedId=await page.locator('.unfinished-turn').getAttribute('data-turn');
  assert.equal(await page.textContent('.question-bubble'),question);
  assert.ok((await page.textContent('.retry-attachment')).includes('原附件'));
  assert.equal(await page.locator('.retry-button').isEnabled(),true);
  await page.locator('.retry-details>summary').first().click();
  assert.ok((await page.textContent('.retry-details')).includes('Preview connection interrupted'));
  await page.fill('#draft','保留正在写的新想法');
  await page.reload();await page.waitForSelector('.retry-panel');
  assert.equal(await page.inputValue('#draft'),'保留正在写的新想法');
  await mkdir('app/build/reports/gui-retry',{recursive:true});
  await page.waitForTimeout(300);
  await page.screenshot({path:'app/build/reports/gui-retry/failed-light.png'});
  await page.evaluate(()=>{const button=document.querySelector('.retry-button');button.click();button.click();});
  await page.waitForSelector('#live-turn');
  assert.equal(await page.locator('.retry-panel').count(),0);
  assert.equal(await page.locator('.question-bubble').count(),1);
  assert.equal(await page.inputValue('#draft'),'保留正在写的新想法');
  await settled();
  assert.ok((await page.textContent('#messages')).includes('RETRY_ATTACHMENT_OK'));
  assert.equal(retries.length,1);assert.deepEqual(retries[0].body,{});
  assert.equal(await page.inputValue('#draft'),'保留正在写的新想法');
  const firstSuccess=await page.locator('.turn').last().getAttribute('data-turn');
  await page.click('#tree-toggle');
  await page.locator(`[data-tree-node="${failedId}"]`).click();
  assert.equal(await page.locator('[data-node-action=retry]').count(),0);
  assert.ok((await page.locator(`[data-tree-node="${failedId}"]`).getAttribute('class')).includes('aborted'));
  await page.locator('.tree-node.current').click();
  assert.equal(await page.locator('[data-node-action=retry]').count(),1);
  await page.click('#tree-close');
  await page.click('.turn-actions [data-retry-turn]');await page.waitForSelector('#live-turn');await settled();
  const latest=await page.locator('.turn').last().getAttribute('data-turn');
  assert.notEqual(latest,firstSuccess);assert.equal(retries.length,2);
  assert.equal(await page.locator('.question-bubble').count(),1);
  assert.equal(await page.inputValue('#draft'),'保留正在写的新想法');
  await page.click('#tree-toggle');await page.locator(`[data-tree-node="${firstSuccess}"]`).click();await page.click('[data-node-action=go]');
  await page.waitForFunction(()=>!document.querySelector('[data-retry-turn]'));
  assert.equal(await page.locator('[data-retry-turn]').count(),0);
  await page.click('#tree-toggle');await page.locator(`[data-tree-node="${latest}"]`).click();await page.click('[data-node-action=go]');
  await page.waitForSelector('.turn-actions [data-retry-turn]');

  // A request-ack timeout is reconciled against core; it never submits another retry.
  await page.evaluate(()=>{window.__originalTimeout=window.setTimeout;window.setTimeout=(fn,ms,...args)=>window.__originalTimeout(fn,ms===30000?120:ms,...args);});
  const delayAck=async route=>{const response=await route.fetch();if(route.request().postDataJSON().op==='retry')await new Promise(resolve=>setTimeout(resolve,800));await route.fulfill({response});};
  await page.route('**/rpc',delayAck);
  await page.click('.turn-actions [data-retry-turn]');
  await page.waitForTimeout(220);
  assert.equal(await page.locator('#stop-generation').isVisible(),true);
  assert.equal(await page.locator('.retry-panel').count(),0);
  await settled();await page.waitForTimeout(900);
  assert.equal(retries.length,3);
  await page.unroute('**/rpc',delayAck);await page.evaluate(()=>{window.setTimeout=window.__originalTimeout;});

  await page.fill('#draft','retry-tool 模拟工具之后的连接失败');await page.click('#send');
  await page.waitForSelector('.retry-panel');await settled();
  const before=retries.length;
  await page.click('.retry-button');await page.waitForSelector('#confirm');
  assert.ok((await page.textContent('.dialog-description')).includes('文件改动不会自动撤销'));
  assert.equal(retries.length,before);
  await page.click('#cancel');assert.equal(retries.length,before);
  await page.click('.retry-button');await page.click('#confirm');
  await page.waitForSelector('#live-turn');await settled();
  assert.equal(retries.length,before+1);
  assert.equal(await page.locator('.retry-panel').count(),0);

  await page.fill('#draft','retry-stop 等待期间停止');await page.click('#send');
  await page.waitForFunction(()=>!document.getElementById('stop-generation').hidden);
  await page.click('#stop-generation');await page.waitForSelector('.retry-panel');await settled();
  await page.evaluate(()=>kaipi.receive({event:'disconnected',data:'test disconnect'}));
  assert.equal(await page.locator('.retry-button').isDisabled(),true);
  await page.click('#retry-engine');await page.waitForSelector('.retry-panel');
  assert.equal(await page.locator('.retry-button').isEnabled(),true);
  await page.click('#sidebar-toggle');await page.click('#appearance-button');await page.click('[data-mode=dark]');await page.click('[data-color=clay]');await page.click('#dialog-close');
  await page.click('#language-settings');await page.click('[data-language-setting=en]');await page.click('#sidebar-close');
  assert.ok((await page.textContent('.retry-heading')).includes('This turn did not finish'));
  assert.equal(await page.textContent('.unfinished-turn .question-bubble'),'retry-stop 等待期间停止');
  await page.waitForFunction(()=>document.getElementById('toast').hidden);
  await page.locator('.retry-panel').scrollIntoViewIfNeeded();await page.screenshot({path:'app/build/reports/gui-retry/failed-dark.png'});
  await page.setViewportSize({width:320,height:520});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.retry-panel').evaluate(node=>getComputedStyle(node).animationName),'none');
  assert.deepEqual(errors,[]);
  console.log('PASS: failed/successful retry, attachment snapshots, reload, draft preservation, single flight, ack timeout reconciliation, context restrictions, tool confirmation, stop, reconnect, language and themes.');
} finally {await browser?.close();server.kill('SIGTERM');}
